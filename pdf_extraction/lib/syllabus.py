def get_syllabus_topics(subject_code: str) -> Optional[List[Tuple[str, str]]]:
    """Get the syllabus topic list for a subject code."""
    return SYLLABUS.get(subject_code)


def format_syllabus_for_prompt(subject_code: str) -> Optional[str]:
    """
    Build a prompt-friendly string of syllabus topics for a given subject.

    Example output:
      "B2 Cells, B2.1 Cell structure, B5.1 Plant nutrition (photosynthesis), ..."
    """
    topics = get_syllabus_topics(subject_code)
    if not topics:
        return None
    return ", ".join(f"{code} {topic}" for code, topic in topics)
